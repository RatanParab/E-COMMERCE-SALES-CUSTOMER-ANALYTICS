# PROJECT INTRODUCTION
#
# This project focuses on analyzing real-world e-commerce
# transaction data to understand sales performance, customer
# behavior, product performance, and purchasing trends.
#
# The dataset contains transactional information such as:
# Invoice Number, Product, Quantity, Unit Price, Invoice Date,
# Customer ID, and Country.
#
# The main objective of this project is to perform a complete
# end-to-end Data Analyst workflow and extract meaningful
# business insights from the data.
